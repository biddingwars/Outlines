  function isFinitePoint(p) {
    return Array.isArray(p) && Number.isFinite(p[0]) && Number.isFinite(p[1]);
  }

  /** Signed shoelace area (positive = counter-clockwise in y-up coordinates). */
  function signedArea(ring) {
    let s = 0;
    const n = ring.length;
    for (let i = 0, j = n - 1; i < n; j = i++) {
      s += (ring[j][0] * ring[i][1]) - (ring[i][0] * ring[j][1]);
    }
    return s / 2;
  }

  function area(ring) {
    return Math.abs(signedArea(ring));
  }

  /** Area centroid; falls back to the vertex mean for zero-area rings. */
  function centroid(ring) {
    let a = 0;
    let cx = 0;
    let cy = 0;
    const n = ring.length;
    for (let i = 0, j = n - 1; i < n; j = i++) {
      const f = (ring[j][0] * ring[i][1]) - (ring[i][0] * ring[j][1]);
      a += f;
      cx += (ring[j][0] + ring[i][0]) * f;
      cy += (ring[j][1] + ring[i][1]) * f;
    }
    if (Math.abs(a) < 1e-12) {
      let sx = 0;
      let sy = 0;
      for (const p of ring) {
        sx += p[0];
        sy += p[1];
      }
      return n ? [sx / n, sy / n] : [0, 0];
    }
    return [cx / (3 * a), cy / (3 * a)];
  }

  function bbox(points) {
    let minX = Infinity;
    let minY = Infinity;
    let maxX = -Infinity;
    let maxY = -Infinity;
    for (const p of points) {
      if (p[0] < minX) minX = p[0];
      if (p[1] < minY) minY = p[1];
      if (p[0] > maxX) maxX = p[0];
      if (p[1] > maxY) maxY = p[1];
    }
    return { minX, minY, maxX, maxY, w: maxX - minX, h: maxY - minY };
  }

  function dist(a, b) {
    const dx = a[0] - b[0];
    const dy = a[1] - b[1];
    return Math.sqrt(dx * dx + dy * dy);
  }

  function perimeter(ring, closed = true) {
    let s = 0;
    for (let i = 1; i < ring.length; i++) s += dist(ring[i - 1], ring[i]);
    if (closed && ring.length > 2) s += dist(ring[ring.length - 1], ring[0]);
    return s;
  }

  /** Largest distance from point c to any vertex. */
  function maxRadius(ring, c) {
    let r = 0;
    for (const p of ring) r = Math.max(r, dist(p, c));
    return r;
  }

  function segDistSq(p, a, b) {
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = dx * dx + dy * dy;
    let t = len ? ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len : 0;
    t = t < 0 ? 0 : t > 1 ? 1 : t;
    const x = a[0] + t * dx - p[0];
    const y = a[1] + t * dy - p[1];
    return x * x + y * y;
  }

  /** Ramer–Douglas–Peucker simplification of an open polyline (iterative). */
  function simplify(points, tolerance) {
    if (points.length <= 2) return points.slice();
    const keep = new Uint8Array(points.length);
    keep[0] = 1;
    keep[points.length - 1] = 1;
    const tolSq = tolerance * tolerance;
    const stack = [[0, points.length - 1]];
    while (stack.length) {
      const [s, e] = stack.pop();
      let maxD = -1;
      let idx = -1;
      for (let i = s + 1; i < e; i++) {
        const d = segDistSq(points[i], points[s], points[e]);
        if (d > maxD) {
          maxD = d;
          idx = i;
        }
      }
      if (idx !== -1 && maxD > tolSq) {
        keep[idx] = 1;
        stack.push([s, idx], [idx, e]);
      }
    }
    const out = [];
    for (let i = 0; i < points.length; i++) if (keep[i]) out.push(points[i]);
    return out;
  }

  /** Simplify a closed ring by splitting it at its two most distant vertices. */
  function simplifyRing(ring, tolerance) {
    if (ring.length <= 4) return ring.slice();
    let far = 0;
    let farD = -1;
    for (let i = 1; i < ring.length; i++) {
      const d = dist(ring[0], ring[i]);
      if (d > farD) {
        farD = d;
        far = i;
      }
    }
    const a = simplify(ring.slice(0, far + 1), tolerance);
    const b = simplify(ring.slice(far).concat([ring[0]]), tolerance);
    const out = a.concat(b.slice(1, -1));
    return out.length >= 3 ? out : ring.slice();
  }

  /** Resample a ring (closed) or polyline to n points evenly spaced along its length. */
  function resample(points, n, closed = true) {
    if (points.length < 2 || n < 2) return points.slice();
    const pts = closed ? points.concat([points[0]]) : points;
    const total = perimeter(pts, false);
    if (total === 0) return Array.from({ length: n }, () => points[0].slice());
    const step = total / (closed ? n : n - 1);
    const out = [pts[0].slice()];
    let acc = 0;
    let target = step;
    for (let i = 1; i < pts.length && out.length < n; i++) {
      const a = pts[i - 1];
      const b = pts[i];
      const seg = dist(a, b);
      while (seg > 0 && acc + seg >= target && out.length < n) {
        const t = (target - acc) / seg;
        out.push([a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t]);
        target += step;
      }
      acc += seg;
    }
    while (out.length < n) out.push(pts[pts.length - 1].slice());
    return out;
  }

  /**
   * Lambert azimuthal equal-area projection centred on [lon0, lat0] (degrees).
   * Returns [x, y] in kilometres on a spherical Earth, y pointing north.
   * Used by the outline build tool; the engine works on pre-projected outlines.
   */
  function projectLAEA([lon, lat], [lon0, lat0]) {
    const R = 6371.0088;
    const d = Math.PI / 180;
    const l = (lon - lon0) * d;
    const p = lat * d;
    const p0 = lat0 * d;
    const k = Math.sqrt(2 / (1 + Math.sin(p0) * Math.sin(p) + Math.cos(p0) * Math.cos(p) * Math.cos(l)));
    return [
      R * k * Math.cos(p) * Math.sin(l),
      R * k * (Math.cos(p0) * Math.sin(p) - Math.sin(p0) * Math.cos(p) * Math.cos(l)),
    ];
  }


  // ───────────── engine/raster.js ─────────────
  // Deterministic polygon rasteriser used for shape comparison.
  //
  // Shapes are filled with the non-zero winding rule, so a loop that crosses
  // itself stays filled instead of punching holes, and several strokes are
  // unioned. Sampling happens at pixel centres. Only + - * / are used.

  /**
   * Rasterise rings into an N×N bitmap.
   * @param {number[][][]} rings   rings in source coordinates
   * @param {{scale:number, tx:number, ty:number}} t  maps source → grid: g = p*scale + t
   * @param {number} n             grid size
   * @param {Uint8Array} [out]     optional bitmap to OR into
   */
  function rasterize(rings, t, n, out = new Uint8Array(n * n)) {
    const rows = new Array(n);
    for (const ring of rings) {
      const m = ring.length;
      if (m < 3) continue;
      for (let i = 0, j = m - 1; i < m; j = i++) {
        const x0 = ring[j][0] * t.scale + t.tx;
        const y0 = ring[j][1] * t.scale + t.ty;
        const x1 = ring[i][0] * t.scale + t.tx;
        const y1 = ring[i][1] * t.scale + t.ty;
        if (y0 === y1) continue;
        const dir = y1 > y0 ? 1 : -1;
        const ya = y0 < y1 ? y0 : y1;
        const yb = y0 < y1 ? y1 : y0;
        // Rows whose centre (r + 0.5) lies in [ya, yb).
        let r0 = Math.ceil(ya - 0.5);
        let r1 = Math.ceil(yb - 0.5) - 1;
        if (r0 < 0) r0 = 0;
        if (r1 > n - 1) r1 = n - 1;
        const inv = (x1 - x0) / (y1 - y0);
        for (let r = r0; r <= r1; r++) {
          const yc = r + 0.5;
          const x = x0 + (yc - y0) * inv;
          (rows[r] ||= []).push(x, dir);
        }
      }
    }
    // Winding is summed across all rings passed in one call (so a ring and an
    // oppositely-wound hole cancel). Use rasterizeUnion() to OR independent shapes.
    for (let r = 0; r < n; r++) {
      const row = rows[r];
      if (!row) continue;
      fillRow(row, r, n, out);
    }
    return out;
  }

  function fillRow(row, r, n, out) {
    // Crossings going down (+1) and up (−1) are sorted apart with the native numeric sort
    // and merged (up first on a tie, as before): a wild scribble has thousands per row and a
    // comparator sort was most of the judge's time on hostile input. Same pixels as before.
    const k = row.length / 2;
    let np = 0;
    for (let i = 0; i < k; i++) if (row[2 * i + 1] > 0) np++;
    const down = new Float64Array(np);
    const up = new Float64Array(k - np);
    for (let i = 0, a = 0, b = 0; i < k; i++) {
      if (row[2 * i + 1] > 0) down[a++] = row[2 * i];
      else up[b++] = row[2 * i];
    }
    down.sort();
    up.sort();
    const base = r * n;
    let wind = 0;
    let start = 0;
    for (let a = 0, b = 0; a < down.length || b < up.length; ) {
      let x;
      let d;
      if (b < up.length && (a >= down.length || up[b] <= down[a])) {
        x = up[b++];
        d = -1;
      } else {
        x = down[a++];
        d = 1;
      }
      const prev = wind;
      wind += d;
      if (prev === 0) start = x; // a filled span starts here…
      else if (wind === 0) {
        // …and ends where the winding returns to zero: pixels whose centre c+0.5 lies in [start, x)
        let c0 = Math.ceil(start - 0.5);
        let c1 = Math.ceil(x - 0.5) - 1;
        if (c0 < 0) c0 = 0;
        if (c1 > n - 1) c1 = n - 1;
        for (let c = c0; c <= c1; c++) out[base + c] = 1;
      }
    }
  }

  /** Rasterise each ring independently and OR them (union of shapes). */
  function rasterizeUnion(rings, t, n) {
    const out = new Uint8Array(n * n);
    for (const ring of rings) rasterize([ring], t, n, out);
    return out;
  }

  function countOn(bits) {
    let c = 0;
    for (let i = 0; i < bits.length; i++) c += bits[i];
    return c;
  }

  /** Pixel area and pixel-centre centroid of a bitmap. */
  function moments(bits, n) {
    let c = 0;
    let sx = 0;
    let sy = 0;
    for (let y = 0; y < n; y++) {
      const base = y * n;
      for (let x = 0; x < n; x++) {
        if (bits[base + x]) {
          c++;
          sx += x + 0.5;
          sy += y + 0.5;
        }
      }
    }
    return c ? { area: c, cx: sx / c, cy: sy / c } : { area: 0, cx: 0, cy: 0 };
  }

  /** Intersection and union counts of two equal-size bitmaps. */
  function overlap(a, b) {
    let inter = 0;
    let uni = 0;
    for (let i = 0; i < a.length; i++) {
      const p = a[i];
      const q = b[i];
      inter += p & q;
      uni += p | q;
    }
    return { inter, union: uni };
  }


  // ───────────── engine/scoring.js ─────────────
  // Points: base points from guessing, multiplier from drawing, round score.

  /**
   * The multiplier is the accuracy itself: 70 % accuracy = 70x, a perfect
   * drawing = 100x, never below 1x. (A play-tester asked for exactly this:
   * the number on the plate should be the number you earned.)
   */
  const DEFAULT_CURVE = Object.freeze({ linear: true, max: 100 });

  const DEFAULT_RULES = Object.freeze({
    /** Base points by the clue the place was guessed on (index 0 = clue 1). */
    basePoints: Object.freeze([5, 4, 3, 2, 1]),
    /** Points taken off the base for each wrong guess (the base never drops below 1 once solved). */
    wrongGuessPenalty: 1,
    curve: DEFAULT_CURVE,
  });

  /**
   * The outline gap at which accuracy reaches 0. The gap is the average distance
   * between the drawn line and the real border (both ways), as a share of the
   * place's equal-area radius: a careful sketch is around 0.06–0.10, a plain
   * circle on a compact country 0.10–0.19, a wrong shape 0.3 or more.
   */
  const ZERO_GAP = 0.36;

  /**
   * Accuracy from the outline gap (see judge.outlineGap): 100 % for a perfect
   * outline, falling linearly to 0 % at ZERO_GAP. The same scale for every place,
   * so a place that really is close to a square (Egypt, Colorado) rewards a good
   * square. Rounded to 0.1 %.
   */
  function accuracyFromGap(gap, zeroGap = ZERO_GAP) {
    if (!(gap >= 0) || !Number.isFinite(gap)) return 0;
    const a = 1 - gap / zeroGap;
    const clamped = a < 0 ? 0 : a > 1 ? 1 : a;
    return Math.round(clamped * 1000) / 1000;
  }

  /** Round to two significant figures: 1, 1.4, 12, 130, 1000. */
  function stampValue(m) {
    if (!(m > 0)) return 1;
    if (m < 10) return Math.round(m * 10) / 10;
    if (m < 100) return Math.round(m);
    if (m < 1000) return Math.round(m / 10) * 10;
    return Math.round(m / 100) * 100;
  }

  /** Multiplier for an accuracy in [0, 1]: accuracy × max, rounded, at least 1. */
  function multiplierFor(accuracy, curve = DEFAULT_CURVE) {
    const a = accuracy > 0 ? (accuracy > 1 ? 1 : accuracy) : 0;
    return Math.max(1, Math.round(a * curve.max));
  }

  /** Validate a curve: linear with a whole-number maximum of at least 1. */
  function validateCurve(curve) {
    if (!curve || curve.linear !== true) return 'curve must be linear';
    if (!(Number.isInteger(curve.max) && curve.max >= 1)) return 'curve max must be a whole number ≥ 1';
    return null;
  }

  /**
   * Base points for a solved turn.
   * @param {number|null} solvedAt  clue index (0-based) of the correct guess, or null
   * @param {number} wrong          wrong guesses made before solving
   */
  function basePointsFor(solvedAt, wrong, rules = DEFAULT_RULES) {
    if (solvedAt === null || solvedAt === undefined) return 0;
    const base = rules.basePoints[solvedAt] ?? 0;
    if (!base) return 0;
    return Math.max(1, base - wrong * rules.wrongGuessPenalty);
  }

  function roundScore(base, multiplier) {
    return Math.round(base * multiplier);
  }


  // ───────────── engine/judge.js ─────────────
  // Drawing judge: cleans a finger drawing, fits it onto the real outline
  // (position and size only — never rotation or aspect) and measures overlap
  // as intersection over union on a fixed grid.
  //
  // Deterministic: same strokes in → same numbers out, on any JS engine.




  const JUDGE_DEFAULTS = Object.freeze({
    grid: 160, // minimum comparison grid (pixels per side)
    maxGrid: 512, // thin shapes (Chile, Norway) get a finer grid, up to this
    minWidthPx: 14, // the target's mean width must span at least this many pixels
    frame: 1.6, // half-size of comparison frame, in target max-radii
    maxStrokes: 32,
    maxPoints: 1500, // across all strokes (20 s of finger drawing at 60 Hz ≈ 1200)
    joinGap: 0.08, // join strokes whose ends are closer than this × drawing size
    minArea: 1e-6, // drawings below this fraction of their bbox² count as empty
    maxSpan: 40000, // raster work budget: total rows crossed by the drawing's edges
    scales: [0.92, 0.96, 1, 1.04, 1.08],
    shifts: [-0.04, 0, 0.04], // in target max-radii
    // Tilts tried (cos, sin) for -50° … +50°: a fixed table, so scoring never depends on Math.cos.
    rotations: [
      [1, 0],
      [0.984807753012, -0.173648177667],
      [0.984807753012, 0.173648177667],
      [0.939692620786, -0.342020143326],
      [0.939692620786, 0.342020143326],
      [0.866025403784, -0.5],
      [0.866025403784, 0.5],
      [0.766044443119, -0.642787609687],
      [0.766044443119, 0.642787609687],
      [0.642787609687, -0.766044443119],
      [0.642787609687, 0.766044443119],
    ],
    samples: 256, // boundary samples per shape for the gap measure
    islandShare: 0.35, // drawn shapes smaller than this share of the biggest are ignored
    minBlobGap: 0.04, // floor for a shape's blob gap (near-rectangular states)
    maxBlobGap: 0.2, // ceiling for thin shapes, where a blob is too easy to beat
  });

  /** Flatten an outline stored as [x0,y0,x1,y1,...] into points. */
  function unflatten(flat) {
    const out = [];
    for (let i = 0; i + 1 < flat.length; i += 2) out.push([flat[i], flat[i + 1]]);
    return out;
  }

  /**
   * Clean raw strokes from the canvas.
   * - drops non-finite points and exact consecutive duplicates
   * - caps the stroke count and total point count (deterministic decimation)
   * - chains strokes whose end points nearly meet, so an outline drawn in
   *   several pieces becomes one shape
   * Returns closed rings (closing edge implied), possibly empty.
   */
  function cleanStrokes(strokes, opts = {}) {
    const o = { ...JUDGE_DEFAULTS, ...opts };
    if (!Array.isArray(strokes)) return [];
    let list = [];
    for (const s of strokes.slice(0, o.maxStrokes)) {
      if (!Array.isArray(s)) continue;
      const pts = [];
      for (const p of s) {
        if (!isFinitePoint(p)) continue;
        const q = [+p[0], +p[1]];
        const last = pts[pts.length - 1];
        if (!last || last[0] !== q[0] || last[1] !== q[1]) pts.push(q);
      }
      if (pts.length) list.push(pts);
    }
    const total = list.reduce((s, l) => s + l.length, 0);
    if (total > o.maxPoints) {
      const keepEvery = Math.ceil(total / o.maxPoints);
      list = list.map((l) => l.filter((_, i) => i % keepEvery === 0 || i === l.length - 1));
    }
    if (!list.length) return [];
    const all = list.flat();
    const b = bbox(all);
    const size = Math.max(b.w, b.h);
    return chainStrokes(list, size * o.joinGap);
  }

  function chainStrokes(list, gap) {
    const pool = list.map((l) => l.slice());
    const out = [];
    while (pool.length) {
      let chain = pool.shift();
      let grown = true;
      while (grown) {
        grown = false;
        const head = chain[0];
        const tail = chain[chain.length - 1];
        // Already closed on itself? Stop growing.
        if (chain.length > 2 && dist(head, tail) <= gap) break;
        let best = -1;
        let bestD = gap;
        let mode = 0;
        for (let i = 0; i < pool.length; i++) {
          const s = pool[i];
          const cands = [
            [dist(tail, s[0]), 0], // tail → start
            [dist(tail, s[s.length - 1]), 1], // tail → end (reverse)
            [dist(head, s[s.length - 1]), 2], // end → head
            [dist(head, s[0]), 3], // start → head (reverse)
          ];
          for (const [d, m] of cands) {
            if (d <= bestD) {
              if (d < bestD || best === -1) {
                bestD = d;
                best = i;
                mode = m;
              }
            }
          }
        }
        if (best !== -1) {
          const s = pool.splice(best, 1)[0];
          if (mode === 0) chain = chain.concat(s);
          else if (mode === 1) chain = chain.concat(s.slice().reverse());
          else if (mode === 2) chain = s.concat(chain);
          else chain = s.slice().reverse().concat(chain);
          grown = true;
        }
      }
      out.push(chain);
    }
    return out;
  }

  /**
   * Prepare a target outline once (cached by callers). `outline` is a ring in
   * outline units, y down.
   */
  function prepareTarget(outline, opts = {}) {
    const o = { ...JUDGE_DEFAULTS, ...opts };
    const c = centroid(outline);
    const r = maxRadius(outline, c);
    const half = r * o.frame;
    const a = area(outline);
    const meanWidth = a / (2 * r);
    const grid = Math.min(o.maxGrid, Math.max(o.grid, Math.ceil((o.minWidthPx * 2 * half) / meanWidth)));
    const scale = grid / (2 * half);
    const t = { scale, tx: (half - c[0]) * scale, ty: (half - c[1]) * scale };
    const bits = rasterize([outline], t, grid);
    const m = moments(bits, grid);
    const target = {
      outline,
      centroid: c,
      radius: r,
      area: a,
      frame: t, // outline units → grid
      bits,
      pixels: m.area,
      grid,
      req: Math.sqrt(a / Math.PI), // radius of the circle with the same area
      samples: resample(outline, o.samples),
      baseline: 0,
      blobGap: 0,
    };
    return target;
  }

  function segDist(p, a, b) {
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = dx * dx + dy * dy;
    let t = len ? ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / len : 0;
    t = t < 0 ? 0 : t > 1 ? 1 : t;
    const x = a[0] + t * dx - p[0];
    const y = a[1] + t * dy - p[1];
    return Math.sqrt(x * x + y * y);
  }

  function distToRings(p, rings) {
    let m = Infinity;
    for (const r of rings) {
      for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
        const d = segDist(p, r[j], r[i]);
        if (d < m) m = d;
      }
    }
    return m;
  }

  /**
   * Average gap between two outlines, both ways (symmetric chamfer distance),
   * divided by the target's equal-area radius. 0 = identical; a featureless
   * blob on a compact country is around 0.1.
   */
  function outlineGap(target, rings, n = JUDGE_DEFAULTS.samples) {
    const total = rings.reduce((s, r) => s + perimeter(r), 0);
    if (!(total > 0)) return Infinity;
    const drawn = rings.map((r) => resample(r, Math.max(8, Math.round((n * perimeter(r)) / total))));
    let a = 0;
    for (const p of target.samples) a += distToRings(p, drawn);
    let b = 0;
    let k = 0;
    for (const r of drawn) {
      for (const p of r) {
        b += distToRings(p, [target.samples]);
        k++;
      }
    }
    return (a / target.samples.length + b / k) / 2 / target.req;
  }

  const BLOB_CIRCLE = Array.from({ length: 96 }, (_, i) => {
    // Polygon with fixed vertices; trig here is fine because the result is
    // compared only against itself on this engine (and pinned by golden tests).
    const a = (i / 96) * 2 * Math.PI;
    return [Math.round(10000 * Math.cos(a)) / 10, Math.round(10000 * Math.sin(a)) / 10];
  });
  const BLOB_SQUARE = [[-1000, -1000], [1000, -1000], [1000, 1000], [-1000, 1000]];

  /**
   * How well a featureless blob (circle or square, auto-fitted like any
   * drawing) matches this outline: its best overlap and its smallest gap.
   * Accuracy is scored relative to the blob, so a blind circle earns 1x on a
   * round country too, while drawing real features pays on every shape.
   */
  function blobBaseline(target, opts = {}) {
    const a = judge([BLOB_CIRCLE], target, { ...opts, baseline: false });
    const b = judge([BLOB_SQUARE], target, { ...opts, baseline: false });
    return {
      overlap: Math.round(Math.max(a.iou, b.iou) * 1000) / 1000,
      gap: Math.round(Math.min(a.gap, b.gap) * 10000) / 10000,
    };
  }

  /** Pixel area and centroid of drawing rings in their own coordinates. */
  function measureDrawing(rings, n) {
    const all = rings.flat();
    const b = bbox(all);
    const size = Math.max(b.w, b.h);
    if (!(size > 0)) return null;
    const pad = size * 0.02;
    const scale = n / (size + 2 * pad);
    const t = { scale, tx: (pad - b.minX) * scale, ty: (pad - b.minY) * scale };
    const bits = rasterizeUnion(rings, t, n);
    const m = moments(bits, n);
    if (!m.area) return null;
    return {
      area: m.area / (scale * scale), // in drawing units²
      centroid: [(m.cx - t.tx) / scale, (m.cy - t.ty) / scale],
      bbox: b,
    };
  }

  /**
   * Score a drawing against a prepared target.
   * The drawing is placed by the best overlap (intersection over union), then
   * scored by how closely its outline follows the real one (outlineGap),
   * relative to what a featureless blob achieves on the same shape.
   * @returns {{accuracy:number, overlap:number, iou:number, gap:number, baseline:number, empty:boolean,
   *            fit:{scale:number, tx:number, ty:number}|null, rings:number[][][]}}
   *   overlap:  raw intersection over union, rounded to 0.1 % (0..1)
   *   gap:      average outline gap / equal-area radius (see outlineGap)
   *   accuracy: 0..1, rounded to 0.1 %; a blob scores about 35 %
   *   fit: maps drawing coords → outline units (p*scale + t); invert it to draw
   *        the real outline over the sketch.
   */
  function judge(strokes, target, opts = {}) {
    const o = { ...JUDGE_DEFAULTS, ...opts };
    // Only the main landmass is scored. Extra shapes a player adds (Sicily,
    // Northern Ireland, Tasmania) are ignored when they are much smaller than
    // the main one, so drawing an island never costs points.
    const all = cleanStrokes(strokes, o).filter((r) => r.length >= 3);
    const big = all.reduce((mx, r) => Math.max(mx, area(r)), 0);
    const rings = all.filter((r) => area(r) >= o.islandShare * big);
    const empty = { accuracy: 0, overlap: 0, iou: 0, gap: Infinity, baseline: target.baseline, empty: true, fit: null, rings };
    if (!rings.length) return empty;
    const m = measureDrawing(rings, target.grid);
    if (!m) return empty;
    const bb = m.bbox;
    if (m.area < o.minArea * Math.max(bb.w, bb.h) ** 2) return empty;

    const s0 = Math.sqrt(target.area / m.area);
    if (!(s0 > 0 && Number.isFinite(s0) && Number.isFinite(m.centroid[0]) && Number.isFinite(m.centroid[1]))) return empty;
    const n = target.grid;
    const F = target.frame;
    const [cx, cy] = m.centroid;
    const rotate = (rs, [co, si]) =>
      co === 1 ? rs : rs.map((r) => r.map(([x, y]) => [cx + (x - cx) * co - (y - cy) * si, cy + (x - cx) * si + (y - cy) * co]));
    const base = tame(rings, s0 * F.scale, o.maxSpan, Math.max(bb.w, bb.h));

    // One fit of the drawing (already rotated) at scale k and offset (dx, dy).
    const fitAt = (work, k, dx, dy) => {
      const s = s0 * k;
      const ox = target.centroid[0] + dx * target.radius - cx * s;
      const oy = target.centroid[1] + dy * target.radius - cy * s;
      // drawing → outline units → grid
      const t = { scale: s * F.scale, tx: ox * F.scale + F.tx, ty: oy * F.scale + F.ty };
      const bits = rasterizeUnion(work, t, n);
      const { inter, union } = overlap(bits, target.bits);
      // Area of the drawing that fell outside the frame still counts against it.
      const expected = m.area * t.scale * t.scale;
      const inside = countOn(bits);
      const wb = bbox(work.flat());
      const gx0 = wb.minX * t.scale + t.tx;
      const gy0 = wb.minY * t.scale + t.ty;
      const gx1 = wb.maxX * t.scale + t.tx;
      const gy1 = wb.maxY * t.scale + t.ty;
      const clipped = gx0 < 0 || gy0 < 0 || gx1 > n || gy1 > n ? Math.max(0, expected - inside) : 0;
      const iou = union + clipped > 0 ? inter / (union + clipped) : 0;
      return { iou, scale: s, tx: ox, ty: oy, k, dx, dy };
    };

    // 1. Which way round? A hand-drawn map is rarely held perfectly north-up:
    //    try a few tilts (fixed table, so every engine computes the same thing).
    //    Coarse first (every other entry of the table: 0°, ±20°, ±40°), then the
    //    neighbours of the best one (±10° from it), so ±50° costs what ±30° did.
    let bestRot = null;
    const tried = new Set();
    const tryRot = (k) => {
      if (k < 0 || k >= o.rotations.length || tried.has(k)) return;
      tried.add(k);
      const rot = o.rotations[k];
      const work = rotate(base, rot);
      for (const dx of o.shifts) for (const dy of o.shifts) {
        const f = fitAt(work, 1, dx, dy);
        if (!bestRot || f.iou > bestRot.iou) bestRot = { iou: f.iou, rot, work, k };
      }
    };
    // table order: 0, -10, +10, -20, +20, … so entry k ± 2 is the next tilt out
    for (let k = 0; k < o.rotations.length; k += k === 0 ? 3 : 4) {
      tryRot(k);
      if (k > 0) tryRot(k + 1);
    }
    const near = bestRot.k;
    if (near === 0) {
      tryRot(1);
      tryRot(2);
    } else {
      tryRot(near - 2);
      tryRot(near + 2);
      if (near <= 2) tryRot(0);
    }
    // 2. Size and position at that tilt, then one refinement pass at half step.
    const work = bestRot.work;
    let best = null;
    const tryFit = (k, dx, dy) => {
      const f = fitAt(work, k, dx, dy);
      if (!best || f.iou > best.iou) best = f;
    };
    for (const k of o.scales) for (const dx of o.shifts) for (const dy of o.shifts) tryFit(k, dx, dy);
    const c = best;
    const ks = (o.scales[1] - o.scales[0]) / 2;
    const ds = (o.shifts[1] - o.shifts[0]) / 2;
    for (const a of [-ks, 0, ks]) for (const b of [-ds, 0, ds]) for (const d of [-ds, 0, ds]) {
      if (a || b || d) tryFit(c.k + a, c.dx + b, c.dy + d);
    }

    const iou = best.iou;
    const fit = { scale: best.scale, tx: best.tx, ty: best.ty, cos: bestRot.rot[0], sin: bestRot.rot[1], cx, cy };
    const placed = work.map((r) => r.map(([x, y]) => [x * fit.scale + fit.tx, y * fit.scale + fit.ty]));
    const gap = outlineGap(target, placed, o.samples);
    return {
      accuracy: accuracyFromGap(gap),
      overlap: Math.round(iou * 1000) / 1000,
      iou,
      gap,
      baseline: target.baseline,
      empty: false,
      fit,
      rings,
    };
  }

  /**
   * Keep raster work bounded. Real outlines cross a few thousand grid rows in
   * total; a frantic scribble can cross hundreds of thousands. Such drawings are
   * simplified (deterministically) until they fit the budget.
   */
  function tame(rings, gridScale, budget, size) {
    const span = (rs) => {
      let s = 0;
      for (const r of rs) for (let i = 0, j = r.length - 1; i < r.length; j = i++) s += Math.abs(r[i][1] - r[j][1]);
      return s * gridScale;
    };
    let out = rings;
    let tol = size / 200;
    while (span(out) > budget && tol < size) {
      out = rings.map((r) => simplifyRing(r, tol));
      tol *= 2;
    }
    return out;
  }

  /** Map the real outline into drawing (canvas) coordinates using a judge fit (undoing its tilt). */
  function outlineToCanvas(outline, fit) {
    const co = fit.cos ?? 1;
    const si = fit.sin ?? 0;
    const cx = fit.cx ?? 0;
    const cy = fit.cy ?? 0;
    return outline.map(([x, y]) => {
      const qx = (x - fit.tx) / fit.scale - cx;
      const qy = (y - fit.ty) / fit.scale - cy;
      return [cx + qx * co + qy * si, cy - qx * si + qy * co];
    });
  }

  /**
   * Width / height of the drawing area for a place: its bounding box, clamped so
   * thin places (Chile, Norway) get a tall canvas and wide ones (Russia) a wide
   * one, without giving the exact proportions away.
   */
  function drawingAspect(outline, min = 0.55, max = 1.8) {
    const b = bbox(outline);
    const a = b.w / (b.h || 1);
    const soft = Math.sqrt(a); // halfway to the true proportions
    return Math.round(Math.min(max, Math.max(min, soft)) * 100) / 100;
  }

  /** Map a ring from outline units into a square canvas of `size` px with margin. */
  function outlineToBox(outline, size, margin = 0.1) {
    const b = bbox(outline);
    const s = (size * (1 - 2 * margin)) / Math.max(b.w, b.h);
    const ox = (size - b.w * s) / 2 - b.minX * s;
    const oy = (size - b.h * s) / 2 - b.minY * s;
    return outline.map(([x, y]) => [x * s + ox, y * s + oy]);
  }


  // ───────────── engine/names.js ─────────────
  // Name matching and autocomplete across every language of the game.

  const LANGS = Object.freeze(['en', 'de', 'it', 'es', 'fr', 'pt', 'id', 'zh', 'hi', 'ja', 'ko', 'ar', 'th']);
  /** Languages written in a script other than Latin. */
  const NON_LATIN = Object.freeze(['zh', 'hi', 'ja', 'ko', 'ar', 'th']);

  /** Fold a name for comparison: no accents, case, punctuation or articles. Letters of
   * every script are kept (NFC, so Hangul, kana and Devanagari stay whole). */
  function fold(text) {
    return String(text ?? '')
      .normalize('NFKD')
      .replace(/[̀-ͯ]/g, '')
      .normalize('NFC')
      .toLowerCase()
      .replace(/ß/g, 'ss')
      .replace(/æ/g, 'ae')
      .replace(/œ/g, 'oe')
      .replace(/ø/g, 'o')
      .replace(/&/g, ' and ')
      .replace(/['’`´.]/g, '')
      .replace(/[^\p{L}\p{M}\p{N}]+/gu, ' ')
      .trim()
      .replace(/^(the|la|le|les|el|los|las|il|lo|gli|i|die|der|das|l) /, '');
  }

  /**
   * Build a search index for a pack's items.
   * @param {Array<{id:string, names:Object<string,string>, aliases?:string[]}>} items
   */
  function buildIndex(items) {
    const entries = [];
    for (const it of items) {
      const seen = new Set();
      const add = (label, lang) => {
        const key = fold(label);
        if (!key || seen.has(key)) return;
        seen.add(key);
        entries.push({ id: it.id, key, words: key.split(' '), label, lang });
      };
      for (const l of LANGS) if (it.names?.[l]) add(it.names[l], l);
      for (const a of it.aliases ?? []) add(a, null);
    }
    const byKey = new Map();
    for (const e of entries) {
      if (!byKey.has(e.key)) byKey.set(e.key, new Set());
      byKey.get(e.key).add(e.id);
    }
    const names = new Map(items.map((it) => [it.id, it.names]));
    const tiers = new Map(items.map((it) => [it.id, Number.isInteger(it.tier) ? it.tier : 9]));
    return { entries, byKey, names, tiers };
  }

  function editDistanceAtMost1(a, b) {
    if (a === b) return true;
    const la = a.length;
    const lb = b.length;
    if (Math.abs(la - lb) > 1) return false;
    let i = 0;
    let j = 0;
    let edits = 0;
    while (i < la && j < lb) {
      if (a[i] === b[j]) {
        i++;
        j++;
        continue;
      }
      if (++edits > 1) return false;
      if (la > lb) i++;
      else if (lb > la) j++;
      else if (i + 1 < la && a[i] === b[j + 1] && a[i + 1] === b[j]) {
        // transposition
        i += 2;
        j += 2;
      } else {
        i++;
        j++;
      }
    }
    return edits + (la - i) + (lb - j) <= 1;
  }

  /**
   * Resolve typed text to an item id: exact match on any name in any language,
   * else a single unambiguous one-typo match (names of 5+ letters).
   * @returns {string|null}
   */
  function resolve(index, text) {
    const key = fold(text);
    if (!key) return null;
    const exact = index.byKey.get(key);
    if (exact) return exact.size === 1 ? [...exact][0] : null;
    if (key.length < 5) return null;
    const hits = new Set();
    for (const e of index.entries) if (e.key.length >= 5 && editDistanceAtMost1(key, e.key)) hits.add(e.id);
    return hits.size === 1 ? [...hits][0] : null;
  }

  /**
   * Autocomplete. Matches the start of the name or of any word in it, in any
   * language; shows the name in the player's language.
   * @returns {Array<{id:string, label:string, matched:string|null}>}
   */
  function suggest(index, text, lang = 'en', limit = 6) {
    const key = fold(text);
    if (!key) return [];
    const best = new Map();
    for (const e of index.entries) {
      let rank = -1;
      if (e.key === key) rank = 0;
      else if (e.key.startsWith(key)) rank = 1;
      else if (e.words.some((w) => w.startsWith(key))) rank = 2;
      else if (key.length >= 3 && e.key.includes(key)) rank = 3;
      if (rank < 0) continue;
      const prev = best.get(e.id);
      const score = rank * 10 + (e.lang === lang ? 0 : 1);
      if (!prev || score < prev.score) best.set(e.id, { score, e });
    }
    return [...best.values()]
      .map(({ score, e }) => {
        const label = index.names.get(e.id)?.[lang] ?? index.names.get(e.id)?.en ?? e.label;
        return { id: e.id, label, matched: fold(label) === e.key ? null : e.label, score, tier: index.tiers?.get(e.id) ?? 9 };
      })
      // equal matches: the better-known place first ("new" → New York before New Hampshire)
      .sort((a, b) => a.score - b.score || a.tier - b.tier || a.label.localeCompare(b.label))
      .slice(0, limit)
      .map(({ id, label, matched }) => ({ id, label, matched }));
  }


  // ───────────── engine/clues.js ─────────────
  // Clue tests: every clue carries a machine-readable test over an item's facts,
  // so the bot can reason about clues without reading prose, and the pack
  // validator can prove each clue is true of its own place.
  //
  // A test is { f: factKey, <op>: value }. Ops:
  //   eq      fact === value
  //   ne      fact !== value
  //   has     array fact contains value
  //   lacks   array fact does not contain value
  //   all     array fact contains every value in the list
  //   any     array fact contains at least one value in the list
  //   count   array fact has exactly this many entries
  //   in      scalar fact is one of the listed values
  //   same    array fact holds exactly the listed values (any order)
  //   gte     number fact is at least value
  //   lte     number fact is at most value
  //   within  number fact is in the range [lo, hi]
  //   inside  range fact [a, b] lies within [lo, hi]

  const OPS = ['eq', 'ne', 'has', 'lacks', 'all', 'any', 'count', 'in', 'same', 'gte', 'lte', 'within', 'inside'];

  function opOf(test) {
    return OPS.find((op) => op in test) ?? null;
  }

  /**
   * Evaluate a test against an item's facts.
   * @returns {boolean|undefined} undefined when the fact is unknown for that item
   */
  function evalTest(test, facts) {
    if (!test || typeof test.f !== 'string') return undefined;
    const v = facts?.[test.f];
    if (v === undefined || v === null) return undefined;
    const op = opOf(test);
    const x = test[op];
    const arr = Array.isArray(v) ? v : null;
    switch (op) {
      case 'eq':
        return v === x;
      case 'ne':
        return v !== x;
      case 'in':
        return Array.isArray(x) && x.includes(v);
      case 'has':
        return arr ? arr.includes(x) : v === x;
      case 'lacks':
        return arr ? !arr.includes(x) : v !== x;
      case 'all':
        return !!arr && Array.isArray(x) && x.every((e) => arr.includes(e));
      case 'any':
        return !!arr && Array.isArray(x) && x.some((e) => arr.includes(e));
      case 'count':
        return !!arr && arr.length === x;
      case 'same':
        return !!arr && Array.isArray(x) && arr.length === x.length && x.every((e) => arr.includes(e));
      case 'gte':
        return typeof v === 'number' && v >= x;
      case 'lte':
        return typeof v === 'number' && v <= x;
      case 'within':
        return typeof v === 'number' && Array.isArray(x) && v >= x[0] && v <= x[1];
      case 'inside':
        return !!arr && arr.length === 2 && Array.isArray(x) && arr[0] >= x[0] && arr[1] <= x[1];
      default:
        return undefined;
    }
  }

  /** Items (from `items`) consistent with every test; unknown facts keep an item in. */
  function filterByTests(items, tests) {
    return items.filter((it) => tests.every((t) => evalTest(t, it.facts) !== false));
  }


  // ───────────── engine/pack.js ─────────────
  // Content packs: validation, preparation and pool selection.
  //
  // A pack is a data module (see packs/*/pack.js) plus an outlines module
  // generated from public-domain map data. Packs are checked on load: a pack
  // that fails validation is refused, never half-loaded.





  /** Clues shown per round: one from each difficulty tier, hardest first. */
  const CLUES_PER_ITEM = 5;
  const TIERS = 5;

  const AND = { en: ' and ', de: ' und ', it: ' e ', es: ' y ', fr: ' et ', pt: ' e ', id: ' dan ', zh: '和', hi: ' और ', ja: 'と', ko: ' 및 ', ar: ' و', th: ' และ ' };
  const COMMA = { zh: '、', ja: '、', ar: '، ' };

  /**
   * Turn a pack's compact clue entries into { tier, text, test } objects.
   * An entry is one of:
   *   { text, test, tier? }             written out (tier defaults to position + 1)
   *   [tier, templateName, param?]       from pack.templates, words from pack.vocab
   *   [tier, slug, { en, de, … }, test?] free text; its test is `test`, else { f: 'tags', has: slug }
   * Free-text slugs are added to the item's facts.tags, so the bot can use them.
   */
  function expandPack(pack) {
    const T = pack.templates ?? {};
    const V = pack.vocab ?? {};
    const word = (vocab, v, l) => {
      const e = V[vocab]?.[v];
      if (!e) throw new Error(`vocab ${vocab}.${v} missing`);
      return e[l] ?? e.en;
    };
    const render = (tpl, param, l) => {
      let x = '';
      if (param !== undefined) {
        if (Array.isArray(param)) {
          const ws = param.map((v) => word(tpl.vocab, v, l));
          x = ws.length > 1 ? `${ws.slice(0, -1).join(COMMA[l] ?? ', ')}${AND[l]}${ws[ws.length - 1]}` : ws[0];
        } else x = tpl.vocab ? word(tpl.vocab, param, l) : String(param);
      }
      const s = tpl.text[l].replaceAll('{x}', x).replace(/\.\.$/, '.');
      return s.charAt(0).toUpperCase() + s.slice(1);
    };
    const items = (pack.items ?? []).map((it) => {
      if (!Array.isArray(it?.clues)) return it;
      const tags = new Set(it.facts?.tags ?? []);
      const clues = it.clues.map((c, k) => {
        if (!Array.isArray(c)) return { ...c, tier: c.tier ?? k + 1 };
        const [tier, name, arg] = c;
        if (T[name]) {
          const tpl = T[name];
          const value = 'value' in tpl ? tpl.value : arg;
          const text = Object.fromEntries(LANGS.map((l) => [l, render(tpl, arg, l)]));
          return { tier, text, test: { f: tpl.f, [tpl.op]: value } };
        }
        tags.add(name);
        // a free sentence may carry its own test ([tier, slug, text, test]); else its tag
        const own = c[3] && typeof c[3] === 'object' && typeof c[3].f === 'string' ? c[3] : null;
        return { tier, text: arg, test: own ?? { f: 'tags', has: name } };
      });
      return { ...it, facts: { ...it.facts, tags: [...tags] }, clues };
    });
    return { ...pack, items };
  }

  function checkText(obj, where, errors) {
    if (!obj || typeof obj !== 'object') {
      errors.push(`${where}: missing translations`);
      return;
    }
    for (const l of LANGS) {
      if (typeof obj[l] !== 'string' || !obj[l].trim()) errors.push(`${where}: missing ${l}`);
    }
  }

  /**
   * Validate a pack against its outlines.
   * @returns {{ok:boolean, errors:string[], warnings:string[]}}
   */
  function validatePack(rawPack, outlines) {
    const errors = [];
    let pack;
    try {
      pack = expandPack(rawPack ?? {});
    } catch (e) {
      return { ok: false, errors: [String(e.message)], warnings: [] };
    }
    if (!rawPack || typeof rawPack !== 'object') return { ok: false, errors: ['pack is not an object'], warnings: [] };
    const warnings = [];
    if (!/^[a-z0-9-]+$/.test(pack.id ?? '')) errors.push('pack.id must be kebab-case');
    checkText(pack.title, 'pack.title', errors);
    if (!Array.isArray(pack.sources) || !pack.sources.length) errors.push('pack.sources: credit the map and fact sources');
    const items = Array.isArray(pack.items) ? pack.items : [];
    if (!items.length) errors.push('pack.items is empty');

    const diffs = pack.difficulties ?? {};
    const diffIds = Object.keys(diffs);
    if (!diffIds.length) errors.push('pack.difficulties is empty');
    for (const d of diffIds) {
      checkText(diffs[d].label, `difficulty ${d}.label`, errors);
      if (!Number.isInteger(diffs[d].maxTier)) errors.push(`difficulty ${d}: maxTier must be an integer`);
    }

    const ids = new Set();
    const names = new Map();
    for (const it of items) {
      const w = `item ${it?.id ?? '?'}`;
      if (!it || typeof it.id !== 'string' || !it.id) {
        errors.push('item without id');
        continue;
      }
      if (ids.has(it.id)) errors.push(`${w}: duplicate id`);
      ids.add(it.id);
      checkText(it.names, `${w}.names`, errors);
      for (const l of LANGS) {
        const k = fold(it.names?.[l]);
        if (k && names.has(k) && names.get(k) !== it.id) errors.push(`${w}: name "${it.names[l]}" collides with ${names.get(k)}`);
        if (k) names.set(k, it.id);
      }
      if (!Number.isInteger(it.tier) || it.tier < 1) errors.push(`${w}: tier must be a positive integer`);
      const geo = outlines?.items?.[it.geo];
      if (!geo) errors.push(`${w}: no outline for geo "${it.geo}"`);
      else {
        const ring = unflatten(geo.pts);
        if (ring.length < 8 || !(area(ring) > 0)) errors.push(`${w}: outline is degenerate`);
        if (geo.share < 0.8 && !it.mainlandOnly) warnings.push(`${w}: main landmass is ${Math.round(geo.share * 100)} % of the area; set mainlandOnly so the rules text says so`);
      }
      if (!it.facts || typeof it.facts !== 'object') errors.push(`${w}: facts missing`);
      if (!Array.isArray(it.clues) || !it.clues.length) {
        errors.push(`${w}: has no clues`);
      } else {
        for (let tier = 1; tier <= TIERS; tier++) {
          if (!it.clues.some((c) => c.tier === tier)) errors.push(`${w}: no clue at tier ${tier}`);
        }
        it.clues.forEach((c, k) => {
          if (!(Number.isInteger(c.tier) && c.tier >= 1 && c.tier <= TIERS)) errors.push(`${w}.clues[${k}]: tier must be 1..${TIERS}`);
          checkText(c.text, `${w}.clues[${k}].text`, errors);
          if (!c.test || !opOf(c.test)) errors.push(`${w}.clues[${k}]: test missing or has no operator`);
          else {
            const r = evalTest(c.test, it.facts);
            if (r !== true) errors.push(`${w}.clues[${k}]: test ${JSON.stringify(c.test)} is ${r === undefined ? 'unknown' : 'false'} for its own facts`);
          }
          if (/\d{4,}|\d+(\.\d+)?\s?(km|million|%|mi\b)/i.test(c.text?.en ?? '')) warnings.push(`${w}.clues[${k}]: looks like a raw statistic`);
        });
        const texts = it.clues.map((c) => c.text?.en);
        if (new Set(texts).size !== texts.length) errors.push(`${w}: two clues say the same thing`);
      }
      checkText(it.fact, `${w}.fact`, errors);
    }

    // Clues must identify their place: every last-tier clue, on its own, fits
    // only that place, so any five drawn for a round single it out.
    for (const it of items) {
      if (!Array.isArray(it.clues)) continue;
      it.clues.forEach((c, k) => {
        if (c.tier !== TIERS || !c.test) return;
        const others = items.filter((o) => o !== it && evalTest(c.test, o.facts) === true);
        if (others.length) errors.push(`item ${it.id}: final-tier clue ${k} (${JSON.stringify(c.test)}) also fits ${others.map((o) => o.id).join(', ')}`);
      });
    }

    for (const kind of ['early', 'late', 'miss', 'drawGood', 'drawBad']) {
      const list = pack.taunts?.[kind];
      if (!Array.isArray(list) || !list.length) errors.push(`taunts.${kind} is empty`);
      else list.forEach((t, i) => checkText(t, `taunts.${kind}[${i}]`, errors));
    }

    const r = pack.settings?.rounds;
    if (!r || !(r.min >= 1 && r.max >= r.min)) errors.push('settings.rounds needs min ≤ max');
    for (const d of diffIds) {
      const n = items.filter((it) => it.tier <= diffs[d].maxTier).length;
      if (r && n < r.min) errors.push(`difficulty ${d}: only ${n} places, fewer than the minimum ${r.min} rounds`);
      else if (r && n < r.max) warnings.push(`difficulty ${d}: ${n} places, so games cap at ${n} rounds`);
    }
    return { ok: errors.length === 0, errors, warnings };
  }

  /**
   * Validate and prepare a pack for play. Throws when invalid.
   * Outline targets are prepared lazily per item (see targetFor).
   */
  function preparePack(pack, outlines) {
    const v = validatePack(pack, outlines);
    if (!v.ok) {
      const e = new Error(`pack ${pack?.id} is invalid:\n  ${v.errors.join('\n  ')}`);
      e.errors = v.errors;
      throw e;
    }
    const full = expandPack(pack);
    const items = full.items.map((it) => {
      const geo = outlines.items[it.geo];
      return Object.freeze({ ...it, outline: unflatten(geo.pts), centroid: geo.c, lon: geo.c[0], lat: geo.c[1], kmPerUnit: geo.km, mainShare: geo.share });
    });
    const byId = new Map(items.map((it) => [it.id, it]));
    const targets = new Map();
    return Object.freeze({
      ...full,
      items,
      byId,
      index: buildIndex(items),
      warnings: v.warnings,
      targetFor(id) {
        if (!targets.has(id)) targets.set(id, prepareTarget(byId.get(id).outline));
        return targets.get(id);
      },
    });
  }

  /** Item ids playable at a difficulty, in pack order. */
  function poolFor(pack, difficulty) {
    const d = pack.difficulties[difficulty];
    if (!d) throw new Error(`unknown difficulty "${difficulty}"`);
    return pack.items.filter((it) => it.tier <= d.maxTier).map((it) => it.id);
  }

  /** True when an item has a position (the globe on the results screen uses it). */
  function hasCoords(item) {
    return !!item && Number.isFinite(item.lat) && Number.isFinite(item.lon);
  }

  /**
   * Pick the clues for one round: one per tier, hardest first, at random from
   * each tier's pool (rng: a seeded generator), skipping sentences in `shown`
   * (English text) while the tier has others. Returns indices into item.clues.
   */
  // Kinds of fact that say much the same thing: a round shows at most one of each
  // when it can (a second latitude or size clue mostly repeats the first).
  const FAMILY = {
    latMin: 'lat', latMax: 'lat', southOf: 'lat', latRange: 'lat', hemisphere: 'lat',
    tropics: 'lat', equator: 'lat', zone: 'lat',
    size: 'area', areaRankWorld: 'area',
    continent: 'region', subregion: 'region',
    nameLetters: 'name', nameEnd: 'name', nameWords: 'name', nameInitial: 'name',
    capital: 'capital', capLetters: 'capital', capInitial: 'capital',
    official: 'language', lang: 'language', native: 'language',
    // US States
    areaRank: 'area', popRank: 'people', missSide: 'river', missRiver: 'river',
    largest: 'capital', capLargest: 'capital', capTz: 'capital', original13: 'year',
  };

  function clueFamily(clue) {
    const t = clue && clue.test;
    if (!t || !t.f) return 'text:' + (clue && clue.text && clue.text.en);
    if (t.f === 'tags') return 'tag:' + t.has;
    if (t.f.startsWith('areaRank_')) return 'area';
    return FAMILY[t.f] || t.f;
  }

  function pickClues(item, rng, shown = new Set()) {
    const out = [];
    const used = new Set();
    for (let tier = 1; tier <= TIERS; tier++) {
      const all = [];
      item.clues.forEach((c, k) => {
        if (c.tier === tier) all.push(k);
      });
      const fresh = (k) => !shown.has(item.clues[k].text.en);
      const newFam = (k) => !used.has(clueFamily(item.clues[k]));
      // Never a sentence already seen this game if avoidable; then a new kind of fact.
      const tries = [
        all.filter((k) => fresh(k) && newFam(k)),
        all.filter(fresh),
        all.filter(newFam),
        all,
      ];
      const pool = tries.find((x) => x.length);
      const k = pool[rng.int(pool.length)];
      out.push(k);
      used.add(clueFamily(item.clues[k]));
    }
    return out;
  }


  // ───────────── engine/bot.js ─────────────
  // The bot opponent.
  //
  // Guessing: the bot is handed a BotView, which holds the clue tests revealed
  // so far, its own wrong guesses and the list of possible places with their
  // public facts. It never receives the answer. It narrows the list clue by
  // clue and guesses once its confidence passes a threshold set by its hidden
  // temperament and its mood.
  //
  // Drawing: the bot sketches the real outline through a noisy hand model
  // (smoothing that loses peninsulas, wobble, jitter, skew, simplification),
  // with a skill rolled per round. Its sketch goes through the same judge as a
  // human drawing.




  const TEMPERAMENTS = Object.freeze({
    conservative: Object.freeze({ threshold: 0.8 }),
    balanced: Object.freeze({ threshold: 0.5 }),
    aggressive: Object.freeze({ threshold: 0.28 }),
  });

  /** Chance the bot understands clue k (before its per-game knowledge factor). */
  const CLUE_RECALL = Object.freeze([0.45, 0.6, 0.75, 0.9, 1.0]);

  /** Per-game knowledge factor for a bot seat: how well it knows its facts. */
  function rollKnowledge(rng) {
    return rng.range(0.78, 1.0);
  }

  /** Per-round drawing skill in [0, 1]. Shape tuned by tools/tune-curve.mjs. */
  function rollSkill(rng) {
    const s = 0.2 + 0.15 * rng.normal();
    return s < 0.02 ? 0.02 : s > 0.98 ? 0.98 : s;
  }

  /**
   * Mood late in the game. Returns 'bold' when behind the leader, 'cautious'
   * when comfortably ahead, otherwise 'calm'.
   * @param {{round:number, rounds:number, mine:number, others:number[]}} s
   */
  function moodFor({ round, rounds, mine, others }) {
    if (rounds <= 0 || round / rounds < 0.6 || !others.length) return 'calm';
    const best = Math.max(...others);
    if (mine < best) return 'bold';
    if (mine > 0 && mine >= 1.5 * best) return 'cautious';
    return 'calm';
  }

  function thresholdFor(temperament, mood) {
    const base = (TEMPERAMENTS[temperament] ?? TEMPERAMENTS.balanced).threshold;
    if (mood === 'bold') return base * 0.6;
    if (mood === 'cautious') return Math.min(0.95, base * 1.3);
    return base;
  }

  /**
   * Decide what to do at the current clue.
   * @param {object} view BotView: { clueIndex, lastClue, tests[], wrong[], candidates[{id, facts}] }
   * @param {object} mind { temperament, mood, knowledge, seed }  seed is the bot's round stream seed
   * @returns {{type:'guess', id:string, confidence:number, remaining:number}
   *          |{type:'wait', confidence:number, remaining:number}}
   */
  function decide(view, mind) {
    const rng = createRng(mind.seed, 'understand');
    // Which clues has the bot understood? Rolled per clue index, independent of the answer.
    const understood = [];
    for (let k = 0; k < view.tests.length; k++) {
      const p = (CLUE_RECALL[k] ?? 1) * mind.knowledge;
      if (rng.fork(k).chance(p)) understood.push(view.tests[k]);
    }
    const wrong = new Set(view.wrong);
    let cands = view.candidates.filter((c) => !wrong.has(c.id));
    // A place whose facts do not show a clue to be true is ruled out (the answer's own
    // facts always do; facts only some places have, like language, cannot keep others in).
    const narrowed = cands.filter((c) => understood.every((t) => evalTest(t, c.facts) === true));
    // If its memory let it down and nothing fits, fall back to the last clue alone.
    if (narrowed.length) cands = narrowed;
    else if (view.tests.length) {
      const last = view.tests[view.tests.length - 1];
      const f = cands.filter((c) => evalTest(last, c.facts) === true);
      if (f.length) cands = f;
    }
    if (!cands.length) return { type: 'wait', confidence: 0, remaining: 0 };
    // Hunches: a fixed, hidden lean per place for this bot and round.
    let total = 0;
    let top = null;
    for (const c of cands) {
      const w = Math.exp(0.35 * createRng(mind.seed, 'hunch', c.id).normal());
      total += w;
      if (!top || w > top.w || (w === top.w && c.id < top.id)) top = { id: c.id, w };
    }
    const confidence = top.w / total;
    const threshold = thresholdFor(mind.temperament, mind.mood);
    if (view.lastClue || confidence >= threshold) {
      return { type: 'guess', id: top.id, confidence, remaining: cands.length };
    }
    return { type: 'wait', confidence, remaining: cands.length };
  }

  // --- drawing -----------------------------------------------------------------

  function smoothRing(ring, radius) {
    if (radius < 1) return ring;
    const n = ring.length;
    const out = new Array(n);
    for (let i = 0; i < n; i++) {
      let sx = 0;
      let sy = 0;
      for (let k = -radius; k <= radius; k++) {
        const p = ring[(i + k + n) % n];
        sx += p[0];
        sy += p[1];
      }
      out[i] = [sx / (2 * radius + 1), sy / (2 * radius + 1)];
    }
    return out;
  }

  /**
   * Sketch an outline like a person drawing from memory.
   * @param {number[][]} outline  ring in outline units
   * @param {number} skill        0 (wild) .. 1 (near perfect)
   * @param {object} rng          seeded rng
   * @param {number} [size=1000]  canvas size in px
   * @returns {number[][][]} strokes in canvas px
   */
  function sketch(outline, skill, rng, size = 1000) {
    const u = 1 - skill;
    const n = 180;
    let ring = resample(outline, n);
    const c = centroid(ring);
    const r = maxRadius(ring, c) || 1;
    // Lose detail: peninsulas and bays melt away for weaker hands.
    ring = smoothRing(ring, Math.round(u * u * 26));
    // Global distortion: skew of proportions and a slight tilt.
    const stretch = Math.exp(0.32 * u * rng.normal());
    const tilt = (12 * u * rng.normal() * Math.PI) / 180;
    const cos = Math.cos(tilt);
    const sin = Math.sin(tilt);
    // Low-frequency wobble along the outline.
    const waves = [0, 1, 2].map(() => ({
      k: 2 + rng.int(6),
      amp: rng.range(0.3, 1) * 0.16 * u * u * r,
      ph: rng.range(0, 2 * Math.PI),
    }));
    const jitter = 0.012 * u * r;
    const pts = ring.map(([x, y], i) => {
      let dx = x - c[0];
      let dy = y - c[1];
      const len = Math.sqrt(dx * dx + dy * dy) || 1;
      let off = 0;
      for (const w of waves) off += w.amp * Math.sin((w.k * 2 * Math.PI * i) / n + w.ph);
      dx += (dx / len) * off + jitter * rng.normal();
      dy += (dy / len) * off + jitter * rng.normal();
      dx *= stretch;
      dy /= stretch;
      return [dx * cos - dy * sin, dx * sin + dy * cos];
    });
    const simple = simplifyRing(pts, (0.004 + 0.05 * u * u) * r);
    // Place on the canvas at a random size and position (the judge ignores both).
    const b = bbox(simple);
    const s = (size * rng.range(0.5, 0.8)) / Math.max(b.w, b.h, 1e-9);
    const ox = rng.range(0.1, 0.9) * size - (b.minX + b.w / 2) * s;
    const oy = rng.range(0.1, 0.9) * size - (b.minY + b.h / 2) * s;
    const placed = simple.map(([x, y]) => [Math.round((x * s + ox) * 10) / 10, Math.round((y * s + oy) * 10) / 10]);
    // Sometimes in two strokes with a small gap; the judge rejoins them.
    if (placed.length > 12 && rng.chance(0.3)) {
      const cut = 4 + rng.int(placed.length - 8);
      return [placed.slice(0, cut), placed.slice(cut + 1)];
    }
    return [placed];
  }

  // --- talk --------------------------------------------------------------------

  /**
   * Pick a one-liner. Item-specific lines are preferred when present.
   * @param {object} pack prepared pack
   * @param {string} kind e.g. 'early', 'late', 'miss', 'drawGood', 'drawBad'
   */
  function line(pack, kind, { itemId, lang = 'en', rng }) {
    const item = itemId ? pack.byId.get(itemId) : null;
    const own = item?.taunts?.[kind];
    const pool = (own && own.length ? own : pack.taunts?.[kind]) ?? [];
    if (!pool.length) return '';
    const pick = pool[rng.int(pool.length)];
    const text = pick[lang] ?? pick.en ?? '';
    const name = item ? item.names[lang] ?? item.names.en : '';
    return text.replaceAll('{place}', name);
  }


  // ───────────── engine/game.js ─────────────
  // The game state machine. Pure: (pack, state, action) → new state.
  // No timers, no storage, no screen code. The view runs the clocks and
  // dispatches `clueTimeout` / `submitDrawing` when they run out.
  //
  // Phases, per round:
  //   handoff → clue → draw → reveal   (once per human seat, in turn)
  //   roundEnd                          (after every human has played)
  // then gameOver after the last round. `handoff` only appears in hot-seat
  // games ("pass the phone to …"); bots play their whole turn when the round
  // begins, without seeing the answer, and their turn carries a timeline the
  // view can stage.







  const SEAT_COLORS = Object.freeze(['red', 'black', 'blue', 'green']);
  const SEAT_SHAPES = Object.freeze(['circle', 'square', 'triangle', 'diamond']);
  const MAX_SEATS = 4;
  const LIMITS = Object.freeze({
    rounds: [5, 30],
    clueSeconds: [5, 60],
    drawSeconds: [5, 90],
  });
  const BOT_CANVAS = 1000;

  const clamp = (x, [lo, hi]) => Math.min(hi, Math.max(lo, Math.round(x)));

  /** Normalise and check a game config. Throws on an unplayable config. */
  function normalizeConfig(pack, config = {}) {
    const seats = (config.seats ?? []).map((s, i) => ({
      kind: s.kind === 'bot' ? 'bot' : 'human',
      name: String(s.name ?? '').trim().slice(0, 24) || null,
      color: SEAT_COLORS[i],
      shape: SEAT_SHAPES[i],
    }));
    const humans = seats.filter((s) => s.kind === 'human').length;
    const bots = seats.length - humans;
    if (seats.length > MAX_SEATS) throw new Error(`at most ${MAX_SEATS} seats`);
    if (humans < 1) throw new Error('at least one human seat');
    if (humans === 1 && (bots < 1 || bots > 3)) throw new Error('solo is one player against 1 to 3 bots');
    if (humans > 1 && bots > 2) throw new Error('hot-seat allows at most 2 bots');
    let botNo = 0;
    for (const s of seats) {
      if (s.kind === 'bot') {
        botNo++;
        s.name ??= bots > 1 ? `Bot ${botNo}` : 'Bot';
      } else s.name ??= `Player ${seats.indexOf(s) + 1}`;
    }
    const difficulty = config.difficulty ?? Object.keys(pack.difficulties)[0];
    const pool = poolFor(pack, difficulty);
    const lim = pack.settings?.rounds ?? { min: LIMITS.rounds[0], max: LIMITS.rounds[1] };
    const rounds = Math.min(clamp(config.rounds ?? pack.settings?.rounds?.default ?? 10, [Math.max(LIMITS.rounds[0], lim.min), Math.min(LIMITS.rounds[1], lim.max)]), pool.length);
    const rules = { ...DEFAULT_RULES, ...(config.rules ?? {}) };
    const curveErr = validateCurve(rules.curve);
    if (curveErr) throw new Error(curveErr);
    if (config.practice?.botStyle && !TEMPERAMENTS[config.practice.botStyle]) throw new Error('unknown bot style');
    return {
      packId: pack.id,
      seed: toSeed(config.seed ?? 0),
      difficulty,
      rounds,
      clueSeconds: clamp(config.clueSeconds ?? pack.settings?.clueSeconds ?? 15, LIMITS.clueSeconds),
      drawSeconds: clamp(config.drawSeconds ?? pack.settings?.drawSeconds ?? 20, LIMITS.drawSeconds),
      seats,
      practice: {
        faintOutline: !!config.practice?.faintOutline,
        botStyle: config.practice?.botStyle ?? null,
      },
      rules,
      // Places from the player's recent games: dealt only once the rest of the pool is used.
      // Oldest first; only the newest half of the pool is held back, so every game
      // still draws from at least half of it at random.
      recent: (Array.isArray(config.recent) ? config.recent.filter((id) => typeof id === 'string' && pool.includes(id)) : []).slice(-Math.floor(pool.length / 2)),
    };
  }

  /** Practice games (faint outline, forced bot style) never touch records. */
  function isPractice(cfg) {
    return !!(cfg.practice.faintOutline || cfg.practice.botStyle);
  }

  /** The group a place belongs to for dealing: its continent (countries) or region (US states). */
  function placeGroup(item) {
    return item?.facts?.continent ?? item?.facts?.region ?? '';
  }

  /**
   * Deal places so every continent (or US region) shows up in proportion to its share of the
   * pool, and two places from the same group never follow each other while another group
   * has places left. A beta tester saw 9 European countries in a 30-round game.
   * Each group keeps its own (already shuffled) order; ties are broken at random.
   */
  function spread(pack, ids, rng) {
    if (ids.length < 3) return ids.slice();
    const groups = new Map();
    for (const id of ids) {
      const g = placeGroup(pack.byId.get(id));
      if (!groups.has(g)) groups.set(g, []);
      groups.get(g).push(id);
    }
    if (groups.size < 2) return ids.slice();
    const share = new Map([...groups].map(([g, list]) => [g, list.length / ids.length]));
    const taken = new Map([...groups.keys()].map((g) => [g, 0]));
    const out = [];
    let prev = null;
    while (out.length < ids.length) {
      const open = [...groups.keys()].filter((g) => taken.get(g) < groups.get(g).length);
      const choices = open.length > 1 ? open.filter((g) => g !== prev) : open;
      // the group furthest behind its fair share so far
      const owed = (g) => share.get(g) * (out.length + 1) - taken.get(g);
      let best = -Infinity;
      let pick = [];
      for (const g of choices) {
        const o = owed(g);
        if (o > best + 1e-9) {
          best = o;
          pick = [g];
        } else if (Math.abs(o - best) <= 1e-9) pick.push(g);
      }
      const g = pick[rng.int(pick.length)];
      out.push(groups.get(g)[taken.get(g)]);
      taken.set(g, taken.get(g) + 1);
      prev = g;
    }
    return out;
  }

  function createGame(pack, config) {
    const cfg = normalizeConfig(pack, config);
    const rng = createRng(cfg.seed, 'setup');
    // A random order of the whole pool; places from recent games go to the back, oldest first.
    const recent = new Set(cfg.recent);
    const order = rng.fork('places').shuffle(poolFor(pack, cfg.difficulty));
    const fresh = order.filter((id) => !recent.has(id));
    const spreadRng = rng.fork('spread');
    const places = [...spread(pack, fresh, spreadRng), ...spread(pack, cfg.recent.filter((id) => !fresh.includes(id)), spreadRng)].slice(0, cfg.rounds);
    // Which five clues each round shows: one per tier, drawn from the place's pool,
    // so the same place reads differently from game to game. A sentence already
    // shown this game is not shown again while its tier has another one.
    const shown = new Set();
    const clueSets = places.map((id, r) => {
      const item = pack.byId.get(id);
      const set = pickClues(item, rng.fork('clues', r), shown);
      for (const k of set) shown.add(item.clues[k].text.en);
      return set;
    });
    // Each bot gets a different hidden temperament.
    const temps = rng.fork('temperaments').shuffle(Object.keys(TEMPERAMENTS));
    const bots = {};
    let b = 0;
    cfg.seats.forEach((s, i) => {
      if (s.kind !== 'bot') return;
      bots[i] = {
        temperament: cfg.practice.botStyle ?? temps[b++ % temps.length],
        knowledge: rollKnowledge(rng.fork('knowledge', i)),
      };
    });
    const state = {
      v: 1,
      config: cfg,
      places,
      clueSets,
      bots,
      round: 0,
      phase: 'clue',
      queue: [],
      qpos: 0,
      turns: [],
      notice: null,
      log: [],
    };
    return beginRound(pack, state);
  }

  function emptyTurn(seat) {
    return {
      seat,
      clue: 0,
      guesses: [],
      solvedAt: null,
      base: 0,
      rings: null,
      overlap: 0,
      accuracy: 0,
      multiplier: 1,
      score: 0,
      done: false,
    };
  }

  /** Totals so far (completed turns only). */
  function totals(state) {
    const t = state.config.seats.map(() => 0);
    for (const round of state.turns) for (const turn of round) if (turn.done) t[turn.seat] += turn.score;
    return t;
  }

  function beginRound(pack, state) {
    const r = state.round;
    const cfg = state.config;
    const humans = cfg.seats.map((s, i) => (s.kind === 'human' ? i : -1)).filter((i) => i >= 0);
    // Rotate who goes first each round.
    const k = r % humans.length;
    state.queue = humans.slice(k).concat(humans.slice(0, k));
    state.qpos = 0;
    const sums = totals(state);
    state.turns[r] = cfg.seats.map((s, i) => (s.kind === 'bot' ? botTurn(pack, state, i, sums) : emptyTurn(i)));
    state.phase = humans.length > 1 ? 'handoff' : 'clue';
    state.notice = null;
    return state;
  }

  /** The view a bot is given: revealed clue tests, its wrong guesses, all candidates. No answer. */
  function botView(pack, state, clueIndex, wrong) {
    const item = pack.byId.get(state.places[state.round]);
    const played = new Set(state.places.slice(0, state.round));
    return {
      clueIndex,
      lastClue: clueIndex === CLUES_PER_ITEM - 1,
      tests: state.clueSets[state.round].slice(0, clueIndex + 1).map((k) => item.clues[k].test),
      wrong: wrong.slice(),
      candidates: poolFor(pack, state.config.difficulty)
        .filter((id) => !played.has(id))
        .map((id) => ({ id, facts: pack.byId.get(id).facts })),
    };
  }

  function botTurn(pack, state, seat, sums) {
    const cfg = state.config;
    const r = state.round;
    const answer = state.places[r];
    const bot = state.bots[seat];
    const seed = deriveSeed(cfg.seed, 'round', r, 'seat', seat, 'bot');
    const rng = createRng(seed, 'turn');
    const mood = moodFor({ round: r, rounds: cfg.rounds, mine: sums[seat], others: sums.filter((_, i) => i !== seat) });
    const mind = { temperament: bot.temperament, mood, knowledge: bot.knowledge, seed };
    const turn = emptyTurn(seat);
    const timeline = [];
    const wrong = [];
    const clueMs = cfg.clueSeconds * 1000;
    for (let c = 0; c < CLUES_PER_ITEM; c++) {
      const d = decide(botView(pack, state, c, wrong), mind);
      if (d.type === 'guess') {
        const ok = d.id === answer; // checked by the engine, not the bot
        const atMs = Math.round(clueMs * rng.range(0.15, 0.8));
        timeline.push({ clue: c, type: 'guess', id: d.id, ok, atMs });
        turn.guesses.push({ clue: c, id: d.id, ok });
        if (ok) {
          turn.solvedAt = c;
          break;
        }
        wrong.push(d.id);
      } else {
        timeline.push({ clue: c, type: 'wait', atMs: clueMs });
      }
    }
    turn.clue = turn.solvedAt ?? CLUES_PER_ITEM - 1;
    turn.base = basePointsFor(turn.solvedAt, wrong.length, cfg.rules);
    const skill = rollSkill(rng.fork('skill'));
    const strokes = sketch(pack.byId.get(answer).outline, skill, rng.fork('sketch'), BOT_CANVAS);
    Object.assign(turn, judgeTurn(pack, answer, strokes, turn.base, cfg.rules));
    const talk = rng.fork('talk');
    const kind = turn.solvedAt === null ? 'miss' : turn.solvedAt <= 1 ? 'early' : 'late';
    turn.bot = {
      mood,
      timeline,
      // Lines are resolved per language by the view through botLine(); keep the kinds and seeds.
      lines: [
        { kind, seed: talk.int(2 ** 31) },
        { kind: turn.multiplier >= 75 ? 'drawGood' : 'drawBad', seed: talk.int(2 ** 31) },
      ],
      skill: Math.round(skill * 1000) / 1000,
    };
    turn.done = true;
    return turn;
  }

  /** A bot one-liner in the player's language. */
  function botLine(pack, state, round, seat, n = 0, lang = 'en') {
    const t = state.turns[round]?.[seat];
    const l = t?.bot?.lines?.[n];
    if (!l) return '';
    return line(pack, l.kind, { itemId: state.places[round], lang, rng: createRng(l.seed) });
  }

  function roundRings(rings) {
    return rings.map((r) => r.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]));
  }

  function judgeTurn(pack, itemId, strokes, base, rules) {
    const res = judge(strokes, pack.targetFor(itemId));
    const multiplier = multiplierFor(res.accuracy, rules.curve);
    return {
      rings: roundRings(res.rings),
      fit: res.fit,
      overlap: res.overlap,
      accuracy: res.accuracy,
      multiplier,
      score: roundScore(base, multiplier),
    };
  }

  /** The human seat whose turn it is, or null. */
  function activeSeat(state) {
    return ['handoff', 'clue', 'draw', 'reveal'].includes(state.phase) ? state.queue[state.qpos] : null;
  }

  function activeTurn(state) {
    const s = activeSeat(state);
    return s === null ? null : state.turns[state.round][s];
  }

  function advanceClue(state, turn) {
    if (turn.clue < CLUES_PER_ITEM - 1) turn.clue++;
    else {
      turn.base = 0;
      state.phase = 'draw';
    }
  }

  /**
   * Apply an action. Never mutates `state`. Illegal actions return the state
   * unchanged apart from `notice`.
   * Actions:
   *   { type: 'ready' }                         handoff → clue
   *   { type: 'guess', id } | { type: 'guess', text }
   *   { type: 'clueTimeout' }
   *   { type: 'submitDrawing', strokes }        strokes: [[[x,y],...], ...] in canvas px
   *   { type: 'continue' }                      reveal → next, roundEnd → next round
   */
  function step(pack, state, action) {
    const s = structuredClone(state);
    s.notice = null;
    const turn = activeTurn(s);
    const reject = (why) => {
      const out = structuredClone(state);
      out.notice = { type: 'rejected', reason: why, action: action?.type ?? null };
      return out;
    };
    const type = action?.type;
    switch (s.phase) {
      case 'handoff':
        if (type !== 'ready') return reject('expected ready');
        s.phase = 'clue';
        break;
      case 'clue': {
        if (type === 'clueTimeout') {
          advanceClue(s, turn);
          break;
        }
        if (type !== 'guess') return reject('expected guess or clueTimeout');
        const id = action.id && pack.byId.has(action.id) ? action.id : resolve(pack.index, action.text ?? '');
        if (!id) {
          const out = structuredClone(state);
          out.notice = { type: 'unknownPlace', text: String(action.text ?? action.id ?? '') };
          return out;
        }
        if (turn.guesses.some((g) => g.id === id)) {
          const out = structuredClone(state);
          out.notice = { type: 'alreadyGuessed', id };
          return out;
        }
        const ok = id === s.places[s.round];
        turn.guesses.push({ clue: turn.clue, id, ok });
        if (ok) {
          turn.solvedAt = turn.clue;
          turn.base = basePointsFor(turn.clue, turn.guesses.length - 1, s.config.rules);
          s.phase = 'draw';
        } else advanceClue(s, turn);
        break;
      }
      case 'draw': {
        if (type !== 'submitDrawing') return reject('expected submitDrawing');
        Object.assign(turn, judgeTurn(pack, s.places[s.round], action.strokes ?? [], turn.base, s.config.rules));
        turn.done = true;
        s.phase = 'reveal';
        break;
      }
      case 'reveal':
        if (type !== 'continue') return reject('expected continue');
        s.qpos++;
        if (s.qpos < s.queue.length) s.phase = 'handoff';
        else s.phase = 'roundEnd';
        break;
      case 'roundEnd':
        if (type !== 'continue') return reject('expected continue');
        s.round++;
        if (s.round >= s.config.rounds) {
          s.phase = 'gameOver';
          s.queue = [];
        } else beginRound(pack, s);
        break;
      default:
        return reject('game over');
    }
    s.log.push(action);
    return s;
  }

  /** Rebuild a game from its config and action log. */
  function replay(pack, config, actions) {
    let s = createGame(pack, config);
    for (const a of actions) s = step(pack, s, a);
    return s;
  }

  /** Clue texts revealed so far for the active human, in a language. */
  function revealedClues(pack, state, lang = 'en') {
    const t = activeTurn(state);
    if (!t || state.phase === 'handoff') return [];
    const item = pack.byId.get(state.places[state.round]);
    const upto = state.phase === 'clue' ? t.clue : t.solvedAt ?? CLUES_PER_ITEM - 1;
    return state.clueSets[state.round].slice(0, upto + 1).map((k) => item.clues[k].text[lang] ?? item.clues[k].text.en);
  }

  /**
   * End-of-game results. Round scores are all here; the view keeps them behind
   * bars and lifts them one at a time.
   */
  function results(pack, state) {
    if (state.phase !== 'gameOver') throw new Error('results are only available at game over');
    const cfg = state.config;
    const sums = totals(state);
    const seats = cfg.seats.map((seat, i) => {
      const rounds = state.turns.map((r, k) => {
        const t = r[i];
        return {
          itemId: state.places[k],
          solvedAt: t.solvedAt,
          base: t.base,
          accuracy: t.accuracy,
          overlap: t.overlap,
          multiplier: t.multiplier,
          score: t.score,
        };
      });
      const avg = rounds.reduce((a, r) => a + r.accuracy, 0) / Math.max(1, rounds.length);
      return { seat: i, name: seat.name, kind: seat.kind, color: seat.color, shape: seat.shape, total: sums[i], avgAccuracy: Math.round(avg * 1000) / 1000, rounds };
    });
    const order = seats.slice().sort((a, b) => b.total - a.total || b.avgAccuracy - a.avgAccuracy || a.seat - b.seat);
    let rank = 0;
    order.forEach((s, k) => {
      const prev = order[k - 1];
      if (!prev || prev.total !== s.total || prev.avgAccuracy !== s.avgAccuracy) rank = k + 1;
      s.rank = rank;
    });
    let best = null;
    state.turns.forEach((r, k) =>
      r.forEach((t) => {
        if (!best || t.accuracy > best.accuracy) best = { seat: t.seat, round: k, itemId: state.places[k], accuracy: t.accuracy, multiplier: t.multiplier, rings: t.rings, fit: t.fit };
      }),
    );
    const places = state.places.map((id, k) => ({
      itemId: id,
      centroid: pack.byId.get(id).centroid,
      accuracy: Object.fromEntries(state.turns[k].map((t) => [t.seat, t.accuracy])),
    }));
    return {
      seats,
      ranking: order.map((s) => ({ seat: s.seat, rank: s.rank })),
      winners: order.filter((s) => s.rank === 1).map((s) => s.seat),
      best,
      places,
      practice: isPractice(cfg),
    };
  }


  // ───────────── engine/records.js ─────────────
  // The on-device record: won/lost per pack against the bot, and the best
  // drawing per place. Pure functions; the view loads and saves the object.


  const RECORD_VERSION = 1;

  function emptyRecord() {
    return { v: RECORD_VERSION, packs: {}, best: {} };
  }

  const nonNegInt = (x) => (Number.isInteger(x) && x >= 0 ? x : 0);

  /** Accept whatever came out of storage; anything malformed is dropped. */
  function sanitizeRecord(raw) {
    const r = emptyRecord();
    if (!raw || typeof raw !== 'object' || raw.v !== RECORD_VERSION) return r;
    for (const [id, p] of Object.entries(raw.packs ?? {})) {
      if (!/^[a-z0-9-]+$/.test(id) || !p || typeof p !== 'object') continue;
      r.packs[id] = { won: nonNegInt(p.won), lost: nonNegInt(p.lost), tied: nonNegInt(p.tied), streak: Number.isInteger(p.streak) ? p.streak : 0 };
    }
    for (const [key, b] of Object.entries(raw.best ?? {})) {
      if (!b || typeof b !== 'object' || !(b.accuracy >= 0 && b.accuracy <= 1) || !Array.isArray(b.rings)) continue;
      r.best[key] = { accuracy: b.accuracy, name: String(b.name ?? '').slice(0, 24), rings: b.rings, at: String(b.at ?? '') };
    }
    return r;
  }

  function compactRings(rings) {
    return rings.map((ring) => {
      const s = ring.length > 80 ? simplify(ring, 1.5) : ring;
      return s.map(([x, y]) => [Math.round(x), Math.round(y)]);
    });
  }

  /**
   * Fold a finished game into the record.
   * - won/lost only for solo games (one human vs bots); ties counted apart
   * - practice games change nothing
   * Best drawings are kept separately with recordDrawing().
   * @param {object} res  results(pack, state)
   * @param {object} opts { packId }
   */
  function recordGame(record, res, { packId }) {
    if (res.practice) return record;
    const r = structuredClone(record);
    const humans = res.seats.filter((s) => s.kind === 'human');
    if (humans.length === 1) {
      const me = humans[0];
      const p = (r.packs[packId] ??= { won: 0, lost: 0, tied: 0, streak: 0 });
      const top = res.winners;
      if (top.length === 1 && top[0] === me.seat) {
        p.won++;
        p.streak = p.streak > 0 ? p.streak + 1 : 1;
      } else if (top.includes(me.seat)) {
        p.tied++;
      } else {
        p.lost++;
        p.streak = p.streak < 0 ? p.streak - 1 : -1;
      }
    }
    return r;
  }

  /** Keep the best drawing per place; call once per human turn. */
  function recordDrawing(record, { packId, itemId, accuracy, rings, name, at = '' }) {
    if (!rings?.length) return record;
    const key = `${packId}:${itemId}`;
    const prev = record.best[key];
    if (prev && prev.accuracy >= accuracy) return record;
    const r = structuredClone(record);
    r.best[key] = { accuracy, name: String(name ?? '').slice(0, 24), rings: compactRings(rings), at };
    return r;
  }


  // ───────────── engine/gamelog.js ─────────────
  // The optional game log (as in Bidding Wars): off by default, kept on the
  // device only under log:v1, exported by the player as text for analysis.
  // One compact record per game (finished or left), plus the app errors seen
  // while recording. No names, no network. tools/analyze-log.mjs reads it.


  const LOG_KEY = 'log:v1';
  const LOG_MAX_GAMES = 40;
  const LOG_MAX_ERRORS = 30;
  const LOG_MAX_CHARS = 1500000;
  const MAX_POINTS = 80; // per drawn ring, after simplifying

  const r3 = (x) => (Number.isFinite(x) ? Math.round(x * 1000) / 1000 : null);

  /** A drawn ring as at most MAX_POINTS integer points. */
  function compactRing(ring) {
    let pts = ring;
    for (let tol = 1; pts.length > MAX_POINTS && tol < 64; tol *= 1.5) pts = simplifyRing(ring, tol);
    if (pts.length > MAX_POINTS) pts = pts.filter((_, k) => k % Math.ceil(pts.length / MAX_POINTS) === 0);
    return pts.map(([x, y]) => [Math.round(x), Math.round(y)]);
  }

  /**
   * The log record of one game.
   * @param pack   the prepared pack
   * @param state  the game state (finished or not)
   * @param extra  { t, app, lang, kind, end: 'done'|'quit', events: [[ms, round, seat, action, detail]] }
   */
  function gameLog(pack, state, extra = {}) {
    const cfg = state.config;
    const played = state.turns.length;
    return {
      v: 1,
      t: extra.t ?? null,
      app: extra.app ?? null,
      lang: extra.lang ?? null,
      kind: extra.kind ?? null,
      end: extra.end ?? (state.phase === 'gameOver' ? 'done' : 'quit'),
      pack: pack.id,
      level: cfg.difficulty,
      rounds: cfg.rounds,
      clueSeconds: cfg.clueSeconds,
      drawSeconds: cfg.drawSeconds,
      practice: !!(cfg.practice.faintOutline || cfg.practice.botStyle),
      seats: cfg.seats.map((s) => s.kind),
      bots: Object.fromEntries(Object.entries(state.bots).map(([i, b]) => [i, { temperament: b.temperament, knowledge: r3(b.knowledge) }])),
      r: state.places.slice(0, played).map((id, k) => {
        const item = pack.byId.get(id);
        return {
          id,
          clues: state.clueSets[k].map((i) => [item.clues[i].tier, item.clues[i].text.en]),
          turns: (state.turns[k] ?? []).map((t) => ({
            seat: t.seat,
            guesses: t.guesses.map((g) => [g.clue, g.id, g.ok ? 1 : 0]),
            solvedAt: t.solvedAt ?? null,
            base: t.base ?? null,
            accuracy: r3(t.accuracy),
            overlap: r3(t.overlap),
            multiplier: t.multiplier ?? null,
            score: t.score ?? null,
            // the drawing and how the judge placed it (people only; bot sketches can be regenerated)
            rings: cfg.seats[t.seat].kind === 'human' && Array.isArray(t.rings) ? t.rings.map(compactRing) : null,
            fit: cfg.seats[t.seat].kind === 'human' && t.fit ? Object.fromEntries(Object.entries(t.fit).map(([k2, v]) => [k2, r3(v)])) : null,
          })),
        };
      }),
      events: Array.isArray(extra.events) ? extra.events.slice(0, 2000) : [],
    };
  }

  /** Read the stored log: { games, errors }. Anything unreadable gives an empty log. */
  function parseLog(raw) {
    let o = null;
    try {
      o = typeof raw === 'string' ? JSON.parse(raw) : raw;
    } catch {
      o = null;
    }
    const games = Array.isArray(o?.games) ? o.games.filter((g) => g && g.v === 1 && Array.isArray(g.r)) : [];
    const errors = Array.isArray(o?.errors) ? o.errors.filter((e) => e && typeof e.msg === 'string') : [];
    return { v: 1, games, errors };
  }

  function serialise(log) {
    while (log.games.length > LOG_MAX_GAMES) log.games.shift();
    while (log.errors.length > LOG_MAX_ERRORS) log.errors.shift();
    let out = JSON.stringify(log);
    while (out.length > LOG_MAX_CHARS && log.games.length > 1) {
      log.games.shift();
      out = JSON.stringify(log);
    }
    return out;
  }

  /** Add one game record; returns the new stored text (oldest games dropped first). */
  function addGameToLog(raw, game) {
    const log = parseLog(raw);
    log.games.push(game);
    return serialise(log);
  }

  /**
   * Add one app error; the same message again only raises its count.
   * @param err { msg, where, stack, t, app, screen }
   */
  function addErrorToLog(raw, err) {
    const log = parseLog(raw);
    const msg = String(err.msg ?? '').slice(0, 300);
    const same = log.errors.find((e) => e.msg === msg && e.where === (err.where ?? null));
    if (same) {
      same.n = (same.n ?? 1) + 1;
      same.last = err.t ?? null;
    } else {
      log.errors.push({ msg, where: err.where ?? null, stack: String(err.stack ?? '').slice(0, 800), t: err.t ?? null, app: err.app ?? null, screen: err.screen ?? null, n: 1 });
    }
    return serialise(log);
  }


