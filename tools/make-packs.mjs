#!/usr/bin/env node
// Writes pack-countries.js and pack-states.js — each pack as ONE classic script
// (the Bidding Wars way): it calls Packs.register({ data, outlines }) in the
// browser, or module.exports it in Node. Sources: packs/<id>/pack.js (content)
// and packs/<id>/outlines.js (generated geometry); only the outlines the pack
// uses are embedded. tests/engine-sync.test.js fails if these files are stale.
//   node tools/make-packs.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCES = [
  { id: 'countries', dir: 'world' },
  { id: 'states', dir: 'us-states' },
];

export async function buildPack({ id, dir }) {
  const { default: data } = await import(`../packs/${dir}/pack.js`);
  const { default: outlines } = await import(`../packs/${dir}/outlines.js`);
  const used = {};
  for (const it of data.items) used[it.geo] = outlines.items[it.geo];
  const pack = { ...data, id };
  return `/* ${id} — GENERATED by tools/make-packs.mjs from packs/${dir}/. Do not edit.
   ${data.sources.join('\n   ')} */
(function (root, pack) {
  if (typeof module === 'object' && module.exports) module.exports = pack;
  else root.Packs.register(pack);
})(typeof self !== 'undefined' ? self : this, ${JSON.stringify({ data: pack, outlines: { units: outlines.units, items: used } })});
`;
}

const check = process.argv.includes('--check');
let stale = false;
for (const s of SOURCES) {
  const out = await buildPack(s);
  const file = join(root, `pack-${s.id}.js`);
  if (check) {
    let cur = '';
    try {
      cur = readFileSync(file, 'utf8');
    } catch {}
    if (cur !== out) stale = true;
  } else {
    writeFileSync(file, out);
    console.log(`wrote pack-${s.id}.js (${(out.length / 1024).toFixed(0)} KB)`);
  }
}
if (stale) {
  console.error('pack files are out of date: run node tools/make-packs.mjs');
  process.exit(1);
}
