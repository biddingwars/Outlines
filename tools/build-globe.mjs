#!/usr/bin/env node
// Builds the small lon/lat datasets the globe draws (menu and end of game).
//   node tools/build-globe.mjs --world <countries-110m.json> --us <states-10m.json>
// Sources: Natural Earth 1:110m (public domain) via world-atlas@2.0.2;
//          US Census 1:10m (public domain) via us-atlas@3.0.1.
// Output: packs/<id>/globe.js = { items: { code: [[lon,lat,lon,lat,...], ...] } }
// (outer rings only, simplified, 0.1° precision).

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { simplifyRing } from '../engine/geometry.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k) => {
  const i = process.argv.indexOf(`--${k}`);
  return i > 0 ? process.argv[i + 1] : null;
};

function decode(topo) {
  const { scale, translate } = topo.transform;
  return topo.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
    });
  });
}
function ring(arcs, idx) {
  const out = [];
  for (const i of idx) {
    const a = i >= 0 ? arcs[i] : arcs[~i].slice().reverse();
    for (let k = out.length ? 1 : 0; k < a.length; k++) out.push(a[k]);
  }
  return out;
}

function build(file, object, tol, header, out) {
  const topo = JSON.parse(readFileSync(file, 'utf8'));
  const arcs = decode(topo);
  const items = {};
  for (const g of topo.objects[object].geometries) {
    if (!g.id) continue;
    const polys = g.type === 'Polygon' ? [g.arcs] : g.type === 'MultiPolygon' ? g.arcs : [];
    const rings = [];
    for (const p of polys) {
      const r = simplifyRing(ring(arcs, p[0]), tol);
      if (r.length < 4) continue;
      rings.push(r.flatMap(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]));
    }
    if (rings.length) (items[g.id] ??= []).push(...rings);
  }
  const body = Object.keys(items).sort().map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(items[k])},`).join('\n');
  writeFileSync(join(root, out), `${header}\nexport default {\n items: {\n${body}\n },\n};\n`);
  console.log(`wrote ${out}`);
}

if (arg('world')) build(arg('world'), 'countries', 0.25, '// GENERATED by tools/build-globe.mjs. Natural Earth 1:110m (public domain) via world-atlas@2.0.2.', 'packs/world/globe.js');
if (arg('us')) build(arg('us'), 'states', 0.06, '// GENERATED by tools/build-globe.mjs. US Census 1:10m (public domain) via us-atlas@3.0.1.', 'packs/us-states/globe.js');
