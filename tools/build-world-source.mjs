#!/usr/bin/env node
// Writes packs/world/source.js: the facts the World pack builds its clues from,
// for the 196 countries of Bidding Wars (193 UN members, Vatican City, Kosovo, Taiwan).
//   node tools/build-world-source.mjs --countries <world-countries/countries.json> --bw <bw-countries.json>
// Inputs:
//   world-countries@5.1.0 (mledoze/countries, ODbL 1.0): codes, region, subregion,
//     official languages, currencies, land borders, landlocked, area, internet
//     domain, dialling code, native names.
//   Bidding Wars' pack-countries.js and pack-capitals.js (this project's own data):
//     the country list, names and capital names in five languages, population.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (k) => process.argv[process.argv.indexOf(`--${k}`) + 1];
const W = JSON.parse(readFileSync(arg('countries'), 'utf8'));
const B = JSON.parse(readFileSync(arg('bw'), 'utf8'));
const L = ['en', 'de', 'it', 'es', 'fr'];
const TR = { de: 'deu', it: 'ita', es: 'spa', fr: 'fra' };

const out = {};
for (const b of B.countries) {
  const w = W.find((c) => c.cca2 === b.id);
  if (!w) throw new Error(`no data for ${b.id}`);
  const cap = B.capitals.find((c) => c.id === b.id);
  const names = {};
  for (const l of L) names[l] = b.name[l] ?? (l === 'en' ? w.name.common : w.translations?.[TR[l]]?.common ?? b.name.en);
  const capital = cap ? Object.fromEntries(L.map((l) => [l, cap.name[l] ?? cap.name.en])) : w.capital?.[0] ? Object.fromEntries(L.map((l) => [l, w.capital[0]])) : null;
  const idd = w.idd?.suffixes?.length === 1 ? w.idd.root + w.idd.suffixes[0] : null;
  out[w.cca3] = {
    iso2: w.cca2,
    geo: b.id === 'XK' ? 'XK' : w.ccn3,
    names,
    capital,
    alt: (w.altSpellings ?? []).filter((a) => a.length >= 4 && /^[\p{L} '.-]+$/u.test(a) && a !== w.name.common).slice(0, 4),
    region: w.region,
    subregion: w.subregion,
    official: Object.values(w.languages ?? {}),
    currencies: Object.values(w.currencies ?? {}).map((c) => c.name),
    borders: w.borders ?? [],
    landlocked: !!w.landlocked,
    area: w.area,
    pop: b.value,
    tld: w.tld?.[0] ?? null,
    idd,
    native: [...new Set(Object.values(w.name.native ?? {}).map((n) => n.common))],
  };
}
const body = JSON.stringify(out, null, 0).replace(/},"/g, '},\n"');
writeFileSync(join(root, 'packs/world/source.js'), `// GENERATED by tools/build-world-source.mjs. Do not edit by hand.
// Country facts from world-countries 5.1.0 (mledoze/countries), Open Database License 1.0:
// https://github.com/mledoze/countries — this extract is likewise available under the ODbL.
// Names, capital names and population: Bidding Wars (this project's own data).
export default ${body};
`);
console.log(`wrote packs/world/source.js (${Object.keys(out).length} countries)`);
