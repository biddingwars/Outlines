#!/usr/bin/env node
// Writes engine.js — the whole engine as ONE classic script, the way the
// Bidding Wars shell loads it (<script src="engine.js"> → global `Engine`,
// or require('./engine.js') in Node). The source of truth stays in engine/*.js
// (ES modules, unit-tested); tests/engine-sync.test.js fails if engine.js is stale.
//   node tools/make-engine.mjs            write engine.js
//   node tools/make-engine.mjs --check    exit 1 if engine.js is out of date
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = ['rng', 'geometry', 'raster', 'scoring', 'judge', 'names', 'clues', 'pack', 'bot', 'game', 'records'];

export function buildEngine() {
  const names = [];
  let body = '';
  for (const m of ORDER) {
    let src = readFileSync(join(root, 'engine', `${m}.js`), 'utf8');
    src = src.replace(/^import\s[\s\S]*?from\s+'[^']+';\s*$/gm, '');
    src = src.replace(/^export\s+(async\s+function|function|const|let|class)\s+(\w+)/gm, (_, kw, n) => {
      names.push(n);
      return `${kw} ${n}`;
    });
    if (/^\s*(import|export)\s/m.test(src)) throw new Error(`engine/${m}.js: unsupported import/export form`);
    body += `\n  // ───────────── engine/${m}.js ─────────────\n${src.replace(/^/gm, '  ').replace(/^  $/gm, '')}\n`;
  }
  return `/* ============================================================================
   engine.js — GENERATED by tools/make-engine.mjs from engine/*.js. Do not edit.
   The rules of Project X: seeded randomness, outline geometry, the drawing
   judge, scoring, name matching, clue tests, packs, the bot, the game state
   machine and records. Pure: no DOM, no storage, no timers.
   Browser: global \`Engine\`. Node: require('./engine.js').
   ========================================================================== */
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.Engine = api;
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
${body}
  return { ${names.join(', ')} };
});
`;
}

const out = buildEngine();
const file = join(root, 'engine.js');
if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(file, 'utf8');
  } catch {}
  if (cur !== out) {
    console.error('engine.js is out of date: run node tools/make-engine.mjs');
    process.exit(1);
  }
} else if (process.argv[1] && process.argv[1].endsWith('make-engine.mjs')) {
  writeFileSync(file, out);
  console.log(`wrote engine.js (${(out.length / 1024).toFixed(0)} KB)`);
}
